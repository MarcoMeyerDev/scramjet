// Minimal end-to-end tour of the @vivari/core SDK:
//   1. boot a browser-native Node.js VM
//   2. mount a file tree, run a script, and stream its stdout
//   3. start an in-VM HTTP server and preview it in an <iframe>
//
// The page must be cross-origin isolated (COOP + COEP) — see vite.config.ts.

import { Vivari, VivariError, type FileSystemTree, type OutputStream } from "@vivari/core";

const $ = <T extends HTMLElement>(id: string) => document.getElementById(id) as T;

const runStatus = $("run-status");
const runOutput = $<HTMLPreElement>("run-output");
const previewStatus = $("preview-status");
const previewFrame = $<HTMLIFrameElement>("preview");

function append(pre: HTMLPreElement, chunk: string) {
  pre.textContent += chunk;
  pre.scrollTop = pre.scrollHeight;
}

async function stream(proc: { output: OutputStream }, pre: HTMLPreElement) {
  for await (const chunk of proc.output) append(pre, chunk);
}

const project: FileSystemTree = {
  "package.json": {
    file: {
      contents: JSON.stringify(
        { name: "vivari-example", type: "module", private: true },
        null,
        2,
      ),
    },
  },
  "hello.js": {
    file: {
      contents: [
        "import os from 'node:os';",
        "console.log('Hello from Node ' + process.version + ' — in your browser!');",
        "console.log('platform:', process.platform, '| arch:', process.arch);",
        "console.log('cwd:', process.cwd());",
        "for (let i = 1; i <= 3; i++) console.log('tick ' + i);",
      ].join("\n"),
    },
  },
  "server.js": {
    file: {
      contents: [
        "import { createServer } from 'node:http';",
        "const server = createServer((req, res) => {",
        "  res.setHeader('content-type', 'text/html; charset=utf-8');",
        "  res.end('<h1>Served from inside your browser 🎉</h1>' +",
        "    '<p>Request: ' + req.method + ' ' + req.url + '</p>' +",
        "    '<p>This HTML was generated by a Node.js HTTP server running in a Web Worker.</p>');",
        "});",
        "server.listen(3111, () => console.log('listening on http://localhost:3111'));",
      ].join("\n"),
    },
  },
};

function readNetRelayParam(): string | undefined {
  const raw = new URLSearchParams(location.search).get("net");
  if (!raw) return undefined;
  try {
    const u = new URL(raw);
    if (u.protocol !== "ws:" && u.protocol !== "wss:") return undefined;
    const host = u.hostname;
    const loopback = host === "localhost" || host === "[::1]" || /^127\.\d{1,3}\.\d{1,3}\.\d{1,3}$/.test(host);
    return loopback ? u.toString() : undefined;
  } catch {
    return undefined;
  }
}

async function main() {
  runStatus.textContent = "booting the Vivari kernel…";

  // This is the original official SDK example flow: boot, mount, spawn, and
  // start the in-VM server before anything related to Scramjet is loaded.
  const vivari = await Vivari.boot({ netRelay: readNetRelayParam() });
  await vivari.mount(project);

  runStatus.textContent = "running: node hello.js";
  const hello = await vivari.spawn("node", ["hello.js"]);
  await stream(hello, runOutput);
  const code = await hello.exit;
  runStatus.textContent = `node hello.js exited with code ${code}`;

  previewStatus.textContent = "starting: node server.js";
  vivari.on("server-ready", (port, url) => {
    previewStatus.textContent = `server listening on in-VM port ${port} → ${url}`;
    previewFrame.src = url;
    previewFrame.hidden = false;
  });
  const server = await vivari.spawn("node", ["server.js"]);
  void stream(server, runOutput);

  // ONLY NOW load Scramjet. The Vivari SDK itself above is the original SDK
  // example flow; Scramjet is added afterward as the second stage of the test.
  const scramjetStatus = document.createElement("p");
  scramjetStatus.textContent = `Original Vivari SDK loaded. crossOriginIsolated=${globalThis.crossOriginIsolated}. Loading Scramjet…`;
  document.body.appendChild(scramjetStatus);

  const scramjetFrame = document.createElement("iframe");
  scramjetFrame.src = "http://localhost:4141/";
  scramjetFrame.title = "Scramjet loaded after original Vivari SDK";
  scramjetFrame.credentialless = true;
  scramjetFrame.style.width = "640px";
  scramjetFrame.style.height = "520px";
  scramjetFrame.style.border = "1px solid #888";
  scramjetFrame.onload = () => {
    // The Scramjet iframe is intentionally cross-origin, so do not inspect its
    // DOM/location from the Vivari page. The load event itself is the browser
    // signal that the child document loaded; the child is verified separately
    // with the browser's visible rendering and network result.
    scramjetStatus.textContent = `Original Vivari SDK loaded → Scramjet iframe loaded. crossOriginIsolated=${globalThis.crossOriginIsolated}`;
  };
  scramjetFrame.onerror = () => {
    scramjetStatus.textContent = "Original Vivari SDK loaded → Scramjet iframe failed to load";
  };
  document.body.appendChild(scramjetFrame);

  // Control test: load the raw external site directly from the same
  // cross-origin-isolated Vivari document, with NO Scramjet proxy.
  const rawStatus = document.createElement("p");
  rawStatus.textContent = "Control test: loading raw https://example.com/ directly…";
  document.body.appendChild(rawStatus);

  const rawFrame = document.createElement("iframe");
  rawFrame.src = "https://example.com/";
  rawFrame.title = "Raw example.com control test without Scramjet";
  rawFrame.style.width = "640px";
  rawFrame.style.height = "300px";
  rawFrame.style.border = "1px solid #d33";
  rawFrame.onload = () => {
    rawStatus.textContent = "Control test: raw https://example.com/ iframe load event fired — inspect browser network/console to see whether COEP allowed the document.";
  };
  rawFrame.onerror = () => {
    rawStatus.textContent = "Control test: raw https://example.com/ iframe was rejected/failed.";
  };
  document.body.appendChild(rawFrame);
}

main().catch((err) => {
  const code = err instanceof VivariError ? err.code : "UNKNOWN";
  const message = err instanceof Error ? err.message : String(err);
  runStatus.textContent = "Failed to boot Vivari.";
  append(runOutput, `\n[${code}] ${message}\n`);
  previewStatus.textContent = "unavailable";
  console.error(err);
});
